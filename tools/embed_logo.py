#!/usr/bin/env python3
"""Regenerates src/logo_data.cpp from resources/logo_round.png.

src/logo_data.cpp holds a built-in copy of the round logo, so the pause menu button can never end
up as the pink "missing texture" square even if the packaged sprite is not found. Run this after
the logo changes:

    python3 tools/embed_logo.py              # 128 x 128 copy (needs Pillow: pip install pillow)
    python3 tools/embed_logo.py --size 256   # another size
    python3 tools/embed_logo.py --size 0     # embed resources/logo_round.png byte for byte (no Pillow)
    python3 tools/embed_logo.py --check      # exit 1 if src/logo_data.cpp is out of date

The header comment of the generated file is written by this script from what it actually did, so it
can not claim a size or a source that is not true.
"""

import argparse
import io
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "resources" / "logo_round.png"
DEFAULT_OUTPUT = ROOT / "src" / "logo_data.cpp"
DEFAULT_SIZE = 128

PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


def png_size(data: bytes):
    """(width, height) from the IHDR chunk, without any imaging library."""
    if data[:8] != PNG_SIGNATURE or data[12:16] != b"IHDR":
        raise ValueError("not a PNG file")
    return struct.unpack(">II", data[16:24])


def build_png(source: Path, size: int):
    """Returns (png_bytes, source_size, final_size, resized)."""
    raw = source.read_bytes()
    src_w, src_h = png_size(raw)
    if src_w != src_h:
        raise ValueError(f"{source} is {src_w} x {src_h}, the logo must be square")

    if size == 0 or size == src_w:
        return raw, src_w, src_w, False

    try:
        from PIL import Image
    except ImportError:
        sys.exit("Pillow is needed to resize the logo (pip install pillow), or use --size 0 to embed the PNG as it is.")

    image = Image.open(io.BytesIO(raw)).convert("RGBA")
    # Pillow resamples RGBA in premultiplied form, so the edge of the round logo gets no dark fringe.
    image = image.resize((size, size), Image.LANCZOS)
    out = io.BytesIO()
    image.save(out, format="PNG", optimize=True)
    return out.getvalue(), src_w, size, True


def render(png: bytes, source: Path, source_size: int, final_size: int, resized: bool) -> str:
    try:
        shown = source.relative_to(ROOT).as_posix()
    except ValueError:
        shown = source.as_posix()

    how = (
        f"downscaled from {source_size} x {source_size}"
        if resized and final_size < source_size
        else f"upscaled from {source_size} x {source_size}"
        if resized
        else "embedded unchanged"
    )
    lines = []
    for i in range(0, len(png), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in png[i:i + 16]) + ",")

    return (
        f"// The round logo ({final_size} x {final_size} PNG) built into the mod, so the pause menu button can never end up\n"
        f"// as the pink and black \"missing texture\" square, even if the packaged sprite is not found.\n"
        f"// Generated by tools/embed_logo.py from {shown} ({how}).\n"
        f"// Do not edit by hand: change the PNG and run the script again.\n"
        f"\n"
        f"#include <cstddef>\n"
        f"\n"
        f"namespace minimum {{\n"
        f"\n"
        f"    extern unsigned char const kLogoRoundPng[];\n"
        f"    extern std::size_t const kLogoRoundPngSize;\n"
        f"\n"
        f"    unsigned char const kLogoRoundPng[] = {{\n"
        + "\n".join(lines)
        + "\n    };\n"
        f"    std::size_t const kLogoRoundPngSize = sizeof(kLogoRoundPng);\n"
        f"\n"
        f"}}\n"
    )


def embedded_png(cpp: Path) -> bytes:
    """The PNG bytes currently inside logo_data.cpp."""
    text = cpp.read_text()
    body = text[text.index("kLogoRoundPng[] = {"):]
    body = body[:body.index("};")]
    return bytes(int(h, 16) for h in re.findall(r"0x([0-9a-fA-F]{2})", body))


def check(source: Path, output: Path, size: int) -> int:
    if not output.exists():
        print(f"{output} does not exist")
        return 1
    current = embedded_png(output)
    cur_w, cur_h = png_size(current)
    expected, _, final_size, _ = build_png(source, size)
    if (cur_w, cur_h) != (final_size, final_size):
        print(f"OUT OF DATE: {output.name} embeds a {cur_w} x {cur_h} PNG, expected {final_size} x {final_size}")
        return 1
    header = output.read_text().split("#include", 1)[0]
    if f"({final_size} x {final_size} PNG)" not in header:
        print(f"OUT OF DATE: the header comment of {output.name} does not say {final_size} x {final_size}")
        return 1
    if size != 0 and final_size != png_size(source.read_bytes())[0]:
        from PIL import Image
        a = Image.open(io.BytesIO(current)).convert("RGBA")
        b = Image.open(io.BytesIO(expected)).convert("RGBA")
        diffs = [abs(x - y) for x, y in zip(a.tobytes(), b.tobytes())]
        mean = sum(diffs) / len(diffs)
        if mean > 1.0:
            print(f"OUT OF DATE: the embedded logo differs from {source.name} (mean channel difference {mean:.2f})")
            return 1
    elif current != expected:
        print(f"OUT OF DATE: the embedded bytes differ from {source.name}")
        return 1
    print(f"OK: {output.name} matches {source.name} ({final_size} x {final_size}, {len(current)} bytes)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE, help="PNG to embed (default: resources/logo_round.png)")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="C++ file to write (default: src/logo_data.cpp)")
    parser.add_argument("--size", type=int, default=DEFAULT_SIZE, help="side in pixels, 0 = embed the source PNG unchanged (default: 128)")
    parser.add_argument("--check", action="store_true", help="do not write, only report whether the output is up to date")
    args = parser.parse_args()

    if args.size < 0 or args.size > 1024:
        parser.error("--size must be 0 or between 1 and 1024")
    if not args.source.exists():
        sys.exit(f"{args.source} not found")

    if args.check:
        return check(args.source, args.output, args.size)

    png, source_size, final_size, resized = build_png(args.source, args.size)
    args.output.write_text(render(png, args.source, source_size, final_size, resized))
    print(f"wrote {args.output}: {final_size} x {final_size} PNG, {len(png)} bytes ({'resized' if resized else 'unchanged'} from {args.source.name}, {source_size} x {source_size})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
